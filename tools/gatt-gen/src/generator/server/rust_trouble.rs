//! Rust for the device, over `trouble-host`: service declarations, the value
//! types they store, and the typed decode of what a client wrote.
//!
//! The generated code is deliberately thin. `trouble-host`'s `#[gatt_service]`
//! macro already builds the attribute table and counts its attributes and CCCDs
//! at compile time, so what is generated here is the declarations the schema
//! implies and nothing else:
//!
//! - a value type per protobuf characteristic, implementing `AsGatt`/`FromGatt`
//!   (bare values are already `u8`, `heapless::String<N>` and so on);
//! - one `#[gatt_service]` struct per proto service, with the declared
//!   properties on each characteristic and no others;
//! - the `#[gatt_server]` struct, and the enum of decoded writes.
//!
//! Two things the attribute table cannot check are emitted as compile-time
//! assertions instead: that a message's bounded encoding fits the characteristic
//! it is stored in, and that a pipe's does not exceed `pipe_msg_max`.

use std::fmt::Write;

use crate::error::Error;
use crate::generator::Output;
use crate::model::{Bare, Characteristic, Gatt, Prop, Service, ValueType};

/// The name the command line uses.
pub const NAME: &str = "rust-trouble";

/// The file this target writes.
pub const OUTPUT_FILE: &str = "gatt_generated.rs";

/// What the generated code needs to know about the crate it lands in.
#[derive(Debug, Clone)]
pub struct Config {
    /// Where the generated protobuf message types live, e.g. `crate::pb::msg`
    /// for a crate whose `micropb` output is re-exported there.
    pub message_module: String,
    /// The name of the generated server struct.
    pub server_name: String,
    /// Backing buffer of a pipe characteristic: the largest chunk that goes in
    /// one notification.
    pub pipe_chunk_max: usize,
    /// Largest message a pipe may carry. `0` skips the check, for schemas whose
    /// pipes are not in use yet.
    pub pipe_msg_max: usize,
    /// How many chunks a pipe may have in flight before it waits for an
    /// acknowledgement. Below 128: a cumulative acknowledgement against a
    /// wrapping `u8` sequence number is only unambiguous below half the space.
    pub window: u8,
    /// No-progress timeout for one transfer, in milliseconds.
    pub xfer_timeout_ms: u32,
    /// The command that regenerates this file, written into its own header so
    /// that whoever finds it does not have to work out how. The tool fills this
    /// in with the invocation it was given.
    pub regenerate_with: Option<String>,
}

impl Default for Config {
    fn default() -> Self {
        Config {
            message_module: "crate::pb::msg".to_string(),
            server_name: "GattServer".to_string(),
            pipe_chunk_max: 244,
            pipe_msg_max: 0,
            window: 8,
            xfer_timeout_ms: 5000,
            regenerate_with: None,
        }
    }
}

/// Generate the firmware-side module for `gatt`.
pub fn generate(gatt: &Gatt, config: &Config) -> Result<Output, Error> {
    let mut out = String::new();
    let version = env!("CARGO_PKG_VERSION");

    // Nothing in this file is an inner attribute: no `//!` docs and no
    // `#![allow]`. An inner attribute is not permitted in an `include!`
    // expansion, so a consumer that generates into `$OUT_DIR` could not mount a
    // file that carried them. A consumer mounts this in a module of its own and
    // allows the lints there, which works however the file gets there.
    let regenerate = match &config.regenerate_with {
        Some(command) => format!("// Regenerate with `{command}` after changing the schema."),
        None => "// Regenerate after changing the schema.".to_string(),
    };
    let _ = writeln!(
        out,
        "// The BLE GATT table for {}.
\
         //
\
         // @generated by gatt-gen {version} -- do not edit.
\
         {regenerate}
\
         // `SCHEMA_HASH` changes with the schema and is what the connect-time
\
         // version check compares.",
        summary(gatt),
    );
    out.push_str(
        "\nuse heapless::Vec;\n\
         use micropb::{MessageDecode, MessageEncode};\n\
         use trouble_host::prelude::*;\n\
         use trouble_host::types::gatt_traits::FromGattError;\n\n",
    );

    let _ = writeln!(
        out,
        "/// A hash of the schema this was generated from: firmware and app built from\n\
         /// the same schema agree, and anything else is caught before a typed value is\n\
         /// believed. Protobuf would otherwise decode a mismatch silently.\n\
         pub const SCHEMA_HASH: u64 = {:#018x};\n\n\
         /// Backing buffer for a pipe characteristic's chunk.\n\
         pub const PIPE_CHUNK_MAX: usize = {};\n",
        gatt.schema_hash(),
        config.pipe_chunk_max
    );

    emit_uuids(&mut out, gatt)?;
    emit_max_lens(&mut out, gatt);

    for characteristic in gatt.characteristics() {
        emit_value_type(&mut out, characteristic, config);
    }

    for service in &gatt.services {
        emit_service(&mut out, service);
    }

    emit_server(&mut out, gatt, config);
    emit_requests(&mut out, gatt, config);
    emit_pipes(&mut out, gatt, config);
    emit_assertions(&mut out, gatt, config);

    while out.ends_with("\n\n") {
        out.pop();
    }

    Ok(Output {
        file_name: OUTPUT_FILE.to_string(),
        source: out,
    })
}

/// The UUIDs the schema declares, so nothing else in the firmware needs a copy of
/// them — the advertisement included.
fn emit_uuids(out: &mut String, gatt: &Gatt) -> Result<(), Error> {
    let wire = |uuid: &str, what: &str| -> Result<[u8; 16], Error> {
        let canonical = crate::uuid::parse_canonical(uuid).ok_or_else(|| {
            Error::Invalid(vec![format!(
                "{what}: uuid {uuid:?} is not a canonical 128-bit UUID"
            )])
        })?;
        Ok(crate::uuid::to_wire_order(&canonical))
    };

    out.push_str(
        "/// The UUIDs the schema declares.\n\
         ///\n\
         /// **Wire order**, which is the reverse of the text quoted in the `.proto`:\n\
         /// `40 88 13 df 5d d4 1f 87 ec 11 cd b0 20 ca 00 00` is\n\
         /// `0000ca20-b0cd-11ec-871f-d45ddf138840` to a client, in the GATT tree and\n\
         /// in advertising data alike. A service's bytes are therefore the array an\n\
         /// advertisement carries (`SERVICE_BYTES`), and its `Uuid` is built from them.\n\
         pub mod uuid {\n\
         \x20   use trouble_host::types::uuid::Uuid;\n\n",
    );

    for service in &gatt.services {
        let name = scream_case(service.short_name());
        let bytes = wire(&service.uuid, &service.proto_name)?;
        let _ = writeln!(
            out,
            "    /// `{}`, as advertising data carries it.\n\
             \x20   pub const {name}_SERVICE_BYTES: [u8; 16] = {};\n\
             \x20   /// `{}`, for the GATT tree.\n\
             \x20   pub const {name}_SERVICE_UUID: Uuid = Uuid::new_long({name}_SERVICE_BYTES);\n\
             \x20   /// `{}`, as a client prints it: the text the schema quotes.\n\
             \x20   pub const {name}_SERVICE_TEXT: &str = \"{}\";\n",
            service.proto_name,
            byte_array(&bytes, 8),
            service.proto_name,
            service.proto_name,
            service.uuid
        );
    }

    for characteristic in gatt.characteristics() {
        let bytes = wire(&characteristic.uuid, &characteristic.path())?;
        let name = format!(
            "{}_{}",
            scream_case(short_name(&characteristic.service)),
            scream_case(&characteristic.name)
        );
        let _ = writeln!(
            out,
            "    /// `{}`.\n\
             \x20   pub const {name}_UUID: Uuid = Uuid::new_long({});\n\
             \x20   /// `{}`, as a client prints it.\n\
             \x20   pub const {name}_TEXT: &str = \"{}\";\n",
            characteristic.path(),
            byte_array(&bytes, 8),
            characteristic.path(),
            characteristic.uuid
        );
    }

    end_module(out);
    Ok(())
}

/// Close a module or struct the way `rustfmt` leaves it: no blank line before the
/// brace.
fn end_module(out: &mut String) {
    while out.ends_with('\n') {
        out.pop();
    }
    out.push_str("\n}\n\n");
}

/// `rustfmt`'s line budget, which the generated file has to satisfy: it is
/// committed, and `cargo fmt --check` covers it like any other source file.
const MAX_WIDTH: usize = 100;

/// A byte array laid out the way `rustfmt` would leave it: one line if it fits,
/// otherwise filled to the width budget. Emitting it unformatted would make the
/// committed file fail the repo's own `cargo fmt --check`.
fn byte_array(bytes: &[u8; 16], indent: usize) -> String {
    let hex: Vec<String> = bytes.iter().map(|byte| format!("0x{byte:02x}")).collect();
    let single = format!("[{}]", hex.join(", "));
    if indent + single.len() <= MAX_WIDTH {
        return single;
    }

    let mut out = String::from("[\n");
    let mut line = String::new();
    for element in hex {
        let candidate = if line.is_empty() {
            format!("{element},")
        } else {
            format!("{line} {element},")
        };
        if !line.is_empty() && indent + candidate.len() > MAX_WIDTH {
            let _ = writeln!(out, "{}{line}", " ".repeat(indent));
            line = format!("{element},");
        } else {
            line = candidate;
        }
    }
    if !line.is_empty() {
        let _ = writeln!(out, "{}{line}", " ".repeat(indent));
    }
    out.push_str(&format!("{}]", " ".repeat(indent.saturating_sub(4))));
    out
}

/// The declared `max_len` of every sized characteristic, so a buffer that has to
/// hold one is sized from the schema rather than from a second number kept in
/// step by hand.
fn emit_max_lens(out: &mut String, gatt: &Gatt) {
    let sized: Vec<(&Characteristic, String)> = gatt
        .characteristics()
        .filter(|characteristic| characteristic.max_len > 0)
        .map(|characteristic| {
            let name = format!(
                "{}_{}",
                scream_case(short_name(&characteristic.service)),
                scream_case(&characteristic.name)
            );
            (characteristic, name)
        })
        .collect();
    if sized.is_empty() {
        return;
    }

    out.push_str(
        "/// The `max_len` each sized characteristic declares. A buffer that holds one\n\
         /// of these values is sized from here, so the schema stays the one place the\n\
         /// number is written down.\n\
         pub mod max_len {\n",
    );
    for (characteristic, name) in sized {
        let _ = writeln!(
            out,
            "    /// `{}.{}`.\n    pub const {name}: usize = {};\n",
            characteristic.service, characteristic.name, characteristic.max_len
        );
    }
    end_module(out);
}

/// One line naming the schema, so the generated file says what it is.
fn summary(gatt: &Gatt) -> String {
    let services: Vec<String> = gatt
        .services
        .iter()
        .map(|service| format!("{} ({})", service.short_name(), service.uuid))
        .collect();
    format!("Schema: {}", services.join(", "))
}

/// The value type a protobuf characteristic stores. A pipe characteristic does
/// not get one: it carries chunks, which the pipe runtime owns.
fn emit_value_type(out: &mut String, characteristic: &Characteristic, config: &Config) {
    let ValueType::Message(message) = characteristic.value_type() else {
        return;
    };
    if characteristic.pipe.is_some() {
        return;
    }

    let ty = value_type_name(characteristic);
    let message_path = message_path(characteristic, config);
    let capacity = characteristic.max_len as usize;

    let _ = writeln!(
        out,
        "/// `{message}` as one GATT attribute value: the message encoded whole, which is\n\
         /// what a single-shot characteristic carries (`max_len` {capacity}).\n\
         ///\n\
         /// `encode` returns `None` only for a message that does not fit, which the\n\
         /// assertion at the end of this file rules out; `decode` returns `None` for\n\
         /// bytes that are not this message at all.\n\
         #[derive(Default)]\n\
         pub struct {ty} {{\n\
         \x20   bytes: Vec<u8, {capacity}>,\n\
         }}\n\n\
         impl {ty} {{\n\
         \x20   /// Encode `message` into a value.\n\
         \x20   pub fn encode(message: &{message_path}) -> Option<Self> {{\n\
         \x20       let mut bytes = Vec::new();\n\
         \x20       bytes.resize({capacity}, 0).ok()?;\n\
         \x20       let mut writer: &mut [u8] = bytes.as_mut_slice();\n\
         \x20       {{\n\
         \x20           let mut encoder = micropb::PbEncoder::new(&mut writer);\n\
         \x20           message.encode(&mut encoder).ok()?;\n\
         \x20       }}\n\
         \x20       let written = {capacity} - writer.len();\n\
         \x20       bytes.truncate(written);\n\
         \x20       Some({ty} {{ bytes }})\n\
         \x20   }}\n\n\
         \x20   /// Encode `message` into an existing value, reusing its buffer: for a\n\
         \x20   /// sender that notifies repeatedly and does not want a value per message.\n\
         \x20   /// Returns false if the message does not fit.\n\
         \x20   pub fn encode_into(&mut self, message: &{message_path}) -> bool {{\n\
         \x20       self.bytes.clear();\n\
         \x20       if self.bytes.resize({capacity}, 0).is_err() {{\n\
         \x20           return false;\n\
         \x20       }}\n\
         \x20       let mut writer: &mut [u8] = self.bytes.as_mut_slice();\n\
         \x20       {{\n\
         \x20           let mut encoder = micropb::PbEncoder::new(&mut writer);\n\
         \x20           if message.encode(&mut encoder).is_err() {{\n\
         \x20               self.bytes.clear();\n\
         \x20               return false;\n\
         \x20           }}\n\
         \x20       }}\n\
         \x20       let written = {capacity} - writer.len();\n\
         \x20       self.bytes.truncate(written);\n\
         \x20       true\n\
         \x20   }}\n\n\
         \x20   /// Decode the value.\n\
         \x20   pub fn decode(&self) -> Option<{message_path}> {{\n\
         \x20       let mut message = {message_path}::default();\n\
         \x20       message.decode_from_bytes(self.bytes.as_slice()).ok()?;\n\
         \x20       Some(message)\n\
         \x20   }}\n\n\
         \x20   /// The value as it goes on the wire.\n\
         \x20   pub fn as_bytes(&self) -> &[u8] {{\n\
         \x20       self.bytes.as_slice()\n\
         \x20   }}\n\
         }}\n\n\
         impl AsGatt for {ty} {{\n\
         \x20   const MIN_SIZE: usize = 0;\n\
         \x20   const MAX_SIZE: usize = {capacity};\n\n\
         \x20   fn as_gatt(&self) -> &[u8] {{\n\
         \x20       self.bytes.as_slice()\n\
         \x20   }}\n\
         }}\n\n\
         impl FromGatt for {ty} {{\n\
         \x20   fn from_gatt(data: &[u8]) -> Result<Self, FromGattError> {{\n\
         \x20       let mut bytes = Vec::new();\n\
         \x20       bytes\n\
         \x20           .extend_from_slice(data)\n\
         \x20           .map_err(|_| FromGattError::InvalidLength)?;\n\
         \x20       Ok({ty} {{ bytes }})\n\
         \x20   }}\n\
         }}\n"
    );
}

/// One `#[gatt_service]`, with one characteristic field each.
fn emit_service(out: &mut String, service: &Service) {
    let _ = writeln!(
        out,
        "/// `{}`.\n#[gatt_service(uuid = \"{}\")]\npub struct {} {{",
        service.proto_name,
        service.uuid,
        service_struct_name(service.short_name())
    );

    for characteristic in &service.characteristics {
        let _ = writeln!(
            out,
            "    /// `{}` ({}), {}.",
            characteristic.name,
            characteristic.uuid,
            describe_value(characteristic)
        );
        if let Some(pipe) = &characteristic.pipe {
            let _ = writeln!(
                out,
                "    ///\n\
                 \x20   /// Pipe {pipe:?}: this value carries chunks and the pipe runtime owns it,\n\
                 \x20   /// so nothing here decodes it as a message.",
            );
        }
        out.push_str(&characteristic_attr(characteristic));
        let _ = writeln!(
            out,
            "    pub {}: {},",
            snake_case(&characteristic.name),
            storage_type(characteristic, characteristic.max_len)
        );
    }

    end_module(out);
}

/// The `#[characteristic(...)]` attribute, split over lines when `rustfmt` would
/// split it (its attribute budget is `attr_fn_like_width`, 70 by default).
fn characteristic_attr(characteristic: &Characteristic) -> String {
    let properties: Vec<&str> = property_names(characteristic);
    let uuid = &characteristic.uuid;

    // The budget is the attribute's *arguments*, not the whole line: that is what
    // `attr_fn_like_width` measures, and matching it is what keeps the committed
    // file format-clean without running rustfmt over it.
    let arguments = if properties.is_empty() {
        format!("uuid = \"{uuid}\"")
    } else {
        format!("uuid = \"{uuid}\", {}", properties.join(", "))
    };
    if arguments.len() <= ATTR_WIDTH {
        return format!("    #[characteristic({arguments})]\n");
    }

    let mut out = format!("    #[characteristic(\n        uuid = \"{uuid}\",\n");
    let last = properties.len().saturating_sub(1);
    for (index, property) in properties.iter().enumerate() {
        let comma = if index == last { "" } else { "," };
        let _ = writeln!(out, "        {property}{comma}");
    }
    out.push_str("    )]\n");
    out
}

/// `rustfmt`'s `attr_fn_like_width`, which decides when an attribute is split.
const ATTR_WIDTH: usize = 70;

/// The `#[gatt_server]` struct: the entry point the firmware builds.
fn emit_server(out: &mut String, gatt: &Gatt, config: &Config) {
    let fields: String = gatt
        .services
        .iter()
        .map(|service| {
            format!(
                "    pub {}: {},\n",
                snake_case(service.short_name()),
                service_struct_name(service.short_name())
            )
        })
        .collect();

    let _ = writeln!(
        out,
        "/// Every service in the schema, and the table they are built into.\n\
         ///\n\
         /// `#[gatt_server]` sums the attribute and CCCD counts at compile time, so adding\n\
         /// a characteristic cannot leave the server a CCCD slot short -- a failure that\n\
         /// shows up as notifications that are accepted and never sent.\n\
         #[gatt_server]\n\
         pub struct {} {{\n{fields}}}\n",
        config.server_name
    );
}

/// The enum of writes the device accepts, and the decode that produces it.
fn emit_requests(out: &mut String, gatt: &Gatt, config: &Config) {
    let written: Vec<&Characteristic> = gatt
        .characteristics()
        .filter(|c| c.is_written() && c.pipe.is_none())
        .collect();

    out.push_str("/// Everything a client can write, decoded according to the schema.\n");
    if written.is_empty() {
        out.push_str("pub enum Request {}\n\n");
        return;
    }

    out.push_str("#[derive(Debug)]\npub enum Request {\n");
    for characteristic in &written {
        let _ = writeln!(
            out,
            "    /// `{}`.\n    {}({}),",
            characteristic.path(),
            pascal_case(&characteristic.name),
            decoded_type(characteristic, config)
        );
    }
    end_module(out);

    let _ = writeln!(
        out,
        "impl Request {{\n\
         \x20   /// The request a write carried, or `None` if it was not one of ours.\n\
         \x20   ///\n\
         \x20   /// Call this **after** the event is accepted: until the server has stored the\n\
         \x20   /// value, the table still holds the last one.\n\
         \x20   pub fn from_event<P: PacketPool>(\n\
         \x20       server: &{}<'_>,\n\
         \x20       event: &GattEvent<'_, '_, P>,\n\
         \x20   ) -> Option<Self> {{\n\
         \x20       let GattEvent::Write(write) = event else {{\n\
         \x20           return None;\n\
         \x20       }};\n\
         \x20       let handle = write.handle();",
        config.server_name
    );

    for characteristic in &written {
        let field = field_path(gatt, characteristic);
        let variant = pascal_case(&characteristic.name);
        match characteristic.value_type() {
            ValueType::Message(_) => {
                let _ = writeln!(
                    out,
                    "        if handle == {field}.handle {{\n\
                     \x20           return server\n\
                     \x20               .get(&{field})\n\
                     \x20               .ok()\n\
                     \x20               .and_then(|value| value.decode())\n\
                     \x20               .map(Request::{variant});\n\
                     \x20       }}"
                );
            }
            ValueType::Bare(_) => {
                let _ = writeln!(
                    out,
                    "        if handle == {field}.handle {{\n\
                     \x20           return server.get(&{field}).ok().map(Request::{variant});\n\
                     \x20       }}"
                );
            }
            ValueType::Empty => {}
        }
    }
    out.push_str("        None\n    }\n}\n\n");
}

/// One module per pipe, holding what the pipe runtime reads: the sizes it was
/// configured with, and the two message codecs.
///
/// The runtime itself is hand-written — it owns tasks, buffers and timers, none of
/// which belong in generated code (SPEC 8) — but it needs to know which
/// characteristic carries which direction, how big a chunk and a message may be,
/// and how to turn the bytes it has reassembled into a message. Those are facts
/// about the schema, so they are generated.
fn emit_pipes(out: &mut String, gatt: &Gatt, config: &Config) {
    for pipe in gatt.pipes() {
        let name = snake_case(pipe.name);
        let to_device = pipe.to_device;
        let to_host = pipe.to_host;
        let inbound = message_of(pipe.to_device, config);
        let outbound = message_of(pipe.to_host, config);

        let _ = writeln!(
            out,
            "/// Pipe `{}`: `{}` in, `{}` out.\n\
             ///\n\
             /// The runtime owns both characteristics (`{}` and `{}`) and hands the\n\
             /// bytes here only to be made into messages: neither value type decodes\n\
             /// anything, because a chunk is not a message.\n\
             pub mod pipe_{name} {{\n\
             \x20   use super::*;\n\
             \n\
             \x20   /// Bytes of payload one chunk may carry, before the frame.\n\
             \x20   pub const CHUNK_MAX: usize = {chunk_max};\n\
             \x20   /// Largest message a transfer may carry, both ways.\n\
             \x20   pub const MESSAGE_MAX: usize = {message_max};\n\
             \x20   /// Chunks in flight at most, before the sender waits.\n\
             \x20   pub const WINDOW: u8 = {window};\n\
             \x20   /// No-progress timeout for one transfer, in milliseconds.\n\
             \x20   pub const XFER_TIMEOUT_MS: u32 = {timeout};{codecs}\n\
             }}\n",
            pipe.name,
            inbound.as_deref().unwrap_or("raw bytes"),
            outbound.as_deref().unwrap_or("raw bytes"),
            to_device.name,
            to_host.name,
            chunk_max = config.pipe_chunk_max,
            message_max = config.pipe_msg_max,
            window = config.window,
            timeout = config.xfer_timeout_ms,
            codecs = codecs(&inbound, &outbound, config),
        );
    }
}

/// The message type a pipe direction carries, if it is a protobuf one.
fn message_of(characteristic: &Characteristic, config: &Config) -> Option<String> {
    match characteristic.value_type() {
        ValueType::Message(_) => Some(message_path(characteristic, config)),
        _ => None,
    }
}

/// Encode and decode helpers for a pipe's two directions, if either is a message.
fn codecs(inbound: &Option<String>, outbound: &Option<String>, _config: &Config) -> String {
    let mut out = String::new();
    let mut emit = |what: &str, path: &str| {
        let short = short_name(path);
        let _ = write!(
            out,
            "\n\n    /// Encode a `{short}` into a chunk buffer, for the sender.\n\
             \x20   /// Returns the length, or `None` if it does not fit.\n\
             \x20   pub fn encode_{what}(message: &{path}, out: &mut [u8]) -> Option<usize> {{\n\
             \x20       let mut writer: &mut [u8] = out;\n\
             \x20       let before = writer.len();\n\
             \x20       let mut encoder = micropb::PbEncoder::new(&mut writer);\n\
             \x20       message.encode(&mut encoder).ok()?;\n\
             \x20       Some(before - writer.len())\n\
             \x20   }}\n\
             \n\
             \x20   /// Decode a reassembled `{short}`. `None` if the bytes are not one.\n\
             \x20   pub fn decode_{what}(bytes: &[u8]) -> Option<{path}> {{\n\
             \x20       let mut message = {path}::default();\n\
             \x20       message.decode_from_bytes(bytes).ok()?;\n\
             \x20       Some(message)\n\
             \x20   }}"
        );
    };
    if let Some(path) = inbound {
        emit("request", path);
    }
    if let Some(path) = outbound {
        emit("response", path);
    }
    out
}

/// A pipe's message has to fit the buffer that reassembles it, and `micropb`
/// knows the worst case for the type, so both ends are compile-time numbers here
/// and a message that could not arrive is a build failure.
///
/// Only pipes: for a single-shot characteristic the type's bound is a worst case
/// the protocol never sends (Calypso's `SyncMessage` carries one 48-sample trace
/// chunk at most, but the type allows any), so asserting it against `max_len`
/// would reject a schema that works. That half is a runtime test instead: encode
/// the largest message the device can build and check it fits.
fn emit_assertions(out: &mut String, gatt: &Gatt, config: &Config) {
    if config.pipe_msg_max == 0 {
        return;
    }

    let mut wrote_header = false;
    for characteristic in gatt.characteristics() {
        if characteristic.pipe.is_none() {
            continue;
        }
        let ValueType::Message(message) = characteristic.value_type() else {
            continue;
        };
        if !wrote_header {
            out.push_str(
                "// A pipe's messages are reassembled into a fixed buffer, and this is where\n\
                 // the bound `micropb` derives from the field options meets that buffer's\n\
                 // size: a message too large to arrive is a build failure rather than a\n\
                 // transfer that stalls part-way.\n",
            );
            wrote_header = true;
        }
        let message_path = format!("{}::{}", config.message_module, short_name(message));
        let _ = writeln!(
            out,
            "const _: () = assert!(\n\
             \x20   micropb::size::max_encoded_size::<{message_path}>() <= {},\n\
             \x20   \"{message} encodes to more than pipe_msg_max ({})\"\n\
             );\n",
            config.pipe_msg_max, config.pipe_msg_max
        );
    }
}

/// `server.battery.level`, which is how the generated struct is reached.
fn field_path(gatt: &Gatt, characteristic: &Characteristic) -> String {
    let service = gatt
        .services
        .iter()
        .find(|service| service.proto_name == characteristic.service)
        .map(|service| service.short_name())
        .unwrap_or_default();
    format!(
        "server.{}.{}",
        snake_case(service),
        snake_case(&characteristic.name)
    )
}

/// `crate::pb::msg::DeviceInfo` for `mydevice.v1.DeviceInfo`.
fn message_path(characteristic: &Characteristic, config: &Config) -> String {
    let ValueType::Message(message) = characteristic.value_type() else {
        return String::new();
    };
    format!("{}::{}", config.message_module, short_name(message))
}

fn short_name(proto_name: &str) -> &str {
    proto_name.rsplit('.').next().unwrap_or(proto_name)
}

/// The type of the value a `Request` variant carries.
fn decoded_type(characteristic: &Characteristic, config: &Config) -> String {
    match characteristic.value_type() {
        ValueType::Message(_) => message_path(characteristic, config),
        ValueType::Bare(bare) => bare_type(*bare, characteristic.max_len).to_string(),
        ValueType::Empty => "()".to_string(),
    }
}

/// The characteristic's storage: the value itself, or a chunk buffer for a pipe.
fn storage_type(characteristic: &Characteristic, len: u32) -> String {
    if characteristic.pipe.is_some() {
        return "Vec<u8, PIPE_CHUNK_MAX>".to_string();
    }
    match characteristic.value_type() {
        ValueType::Message(_) => value_type_name(characteristic),
        ValueType::Bare(bare) => bare_type(*bare, len).to_string(),
        // Rejected by the validator: a characteristic with no direction at all.
        ValueType::Empty => "()".to_string(),
    }
}

fn bare_type(bare: Bare, len: u32) -> String {
    match bare {
        Bare::U8 => "u8".to_string(),
        Bare::U16 => "u16".to_string(),
        Bare::U32 => "u32".to_string(),
        Bare::I8 => "i8".to_string(),
        Bare::I16 => "i16".to_string(),
        Bare::I32 => "i32".to_string(),
        Bare::F32 => "f32".to_string(),
        Bare::Bool => "bool".to_string(),
        // Sized by `max_len`, which the validator requires.
        Bare::Utf8 => format!("HeaplessString<{len}>"),
        Bare::Bytes => format!("Vec<u8, {len}>"),
    }
}

/// The declared properties, in the order `trouble-host`'s attribute lists them.
fn property_names(characteristic: &Characteristic) -> Vec<&'static str> {
    let order = [
        Prop::Read,
        Prop::Write,
        Prop::WriteNoRsp,
        Prop::Notify,
        Prop::Indicate,
    ];
    order
        .iter()
        .filter(|prop| characteristic.props.contains(prop))
        .map(|prop| match prop {
            Prop::Read => "read",
            Prop::Write => "write",
            Prop::WriteNoRsp => "write_without_response",
            Prop::Notify => "notify",
            Prop::Indicate => "indicate",
        })
        .collect()
}

fn describe_value(characteristic: &Characteristic) -> String {
    match characteristic.value_type() {
        ValueType::Bare(bare) => format!("bare {}", bare.name()),
        other => other.describe(),
    }
}

fn value_type_name(characteristic: &Characteristic) -> String {
    format!(
        "{}{}Value",
        pascal_case(short_name(&characteristic.service)),
        pascal_case(&characteristic.name)
    )
}

fn service_struct_name(short: &str) -> String {
    format!("{}Service", pascal_case(short))
}

fn scream_case(name: &str) -> String {
    snake_case(name).to_uppercase()
}

fn snake_case(name: &str) -> String {
    let mut out = String::new();
    for (i, ch) in name.chars().enumerate() {
        if ch.is_uppercase() {
            // `Sync_Requests` is one separator, not two.
            if i != 0 && !out.ends_with('_') {
                out.push('_');
            }
            out.extend(ch.to_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

fn pascal_case(name: &str) -> String {
    let mut out = String::new();
    for part in name.split(['_', '.']) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    out
}
